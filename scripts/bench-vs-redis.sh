#!/usr/bin/env bash
# Cross-system Pareto comparison: astream-broker vs Redis at EQUAL conditions —
# same host, same transport (Unix socket), same durability (one fsync per
# operation), same workload (N single, sequential, durable appends of a 64-byte
# payload). Writes a disclosed-hardware artifact to evidence/bench/broker-vs-redis.md.
#
# This measures the broker against Redis at equal durability: it is an
# ATTACHED ARTIFACT (numbers are machine-specific), not a green CI claim. Re-run it
# anywhere to regenerate. Requires redis-server + redis-benchmark on PATH.
set -euo pipefail
cd "$(dirname "$0")/.."

N="${BENCH_N:-500}"
OUT="evidence/bench/broker-vs-redis.md"
mkdir -p "$(dirname "$OUT")"
DIR="$(mktemp -d)"
SOCK="$DIR/redis.sock"
RPID=""
# Installed before anything else can fail, so neither Redis nor the temp dir
# outlives the run.
cleanup() {
  if [ -n "$RPID" ]; then
    kill "$RPID" 2>/dev/null || true
    wait "$RPID" 2>/dev/null || true
  fi
  rm -rf "$DIR"
}
trap cleanup EXIT

# Redis: AOF on, fsync on EVERY write (matches astream's Strict fsync-per-message),
# RDB off, over a Unix socket — the same transport + durability as astream-broker.
redis-server --unixsocket "$SOCK" --port 0 --appendonly yes --appendfsync always \
  --save '' --dir "$DIR" >/dev/null 2>&1 &
RPID=$!
# Wait (bounded, ~10 s) until Redis answers on the socket. A server that never
# comes up ends the run here instead of being "measured" as nothing.
ready=0
for _ in $(seq 1 200); do
  if redis-cli -s "$SOCK" ping >/dev/null 2>&1; then ready=1; break; fi
  sleep 0.05
done
if [ "$ready" -ne 1 ]; then
  echo "bench-vs-redis: redis-server never answered on $SOCK" >&2
  exit 1
fi

# redis-benchmark prints carriage-return progress lines; the final summary is
# "RPUSH: <rps> requests per second, ...". Split CRs to lines, take the summary.
# Neither tool's stderr is discarded: a failure must say why, not end silently.
REDIS_SEQ=$(redis-benchmark -s "$SOCK" -n "$N" -c 1 -P 1 -t rpush -d 64 -q \
  | tr '\r' '\n' | sed -n 's/^RPUSH: \([0-9.]*\) requests per second.*/\1/p' | head -1)

PIPE_N="${BENCH_PIPE_N:-20000}"
REDIS_PIPE=$(redis-benchmark -s "$SOCK" -n "$PIPE_N" -c 1 -P 512 -t rpush -d 64 -q \
  | tr '\r' '\n' | sed -n 's/^RPUSH: \([0-9.]*\) requests per second.*/\1/p' | head -1)

GC_CLIENTS=32
GC_PER=200
GC_TOTAL=$((GC_CLIENTS * GC_PER))
REDIS_GC=$(redis-benchmark -s "$SOCK" -n "$GC_TOTAL" -c "$GC_CLIENTS" -P 1 -t rpush -d 64 -q \
  | tr '\r' '\n' | sed -n 's/^RPUSH: \([0-9.]*\) requests per second.*/\1/p' | head -1)

# Switch Redis to appendfsync everysec (page-cache write on hot path, matching Relaxed):
redis-cli -s "$SOCK" config set appendfsync everysec >/dev/null
RELAXED_N="${BENCH_RELAXED_N:-20000}"
REDIS_RELAXED=$(redis-benchmark -s "$SOCK" -n "$RELAXED_N" -c 1 -P 1 -t rpush -d 64 -q \
  | tr '\r' '\n' | sed -n 's/^RPUSH: \([0-9.]*\) requests per second.*/\1/p' | head -1)

ASTREAM_SEQ=$(BENCH_N="$N" targo --unverified run --quiet --release --locked -p astream-broker --example broker_microbench \
  | sed -n 's/^METRIC broker_publish_ops_per_sec \([0-9]*\).*/\1/p' | head -1)

ASTREAM_PIPE=$(DURABILITY=strict HORIZON_MS= WINDOW=512 BENCH_N="$PIPE_N" targo --unverified run --quiet --release --locked -p astream-broker --example broker_pipeline_bench \
  | sed -n 's/^METRIC broker_strict_pipeline_ops_per_sec \([0-9]*\).*/\1/p' | head -1)

ASTREAM_GC=$(PRODUCERS="$GC_CLIENTS" BENCH_N="$GC_PER" targo --unverified run --quiet --release --locked -p astream-broker --example broker_groupcommit_bench \
  | sed -n 's/^METRIC broker_groupcommit_ops_per_sec \([0-9]*\).*/\1/p' | head -1)

ASTREAM_RELAXED=$(DURABILITY=relaxed HORIZON_MS= BENCH_N="$RELAXED_N" targo --unverified run --quiet --release --locked -p astream-broker --example broker_durability_bench \
  | sed -n 's/^METRIC broker_relaxed_ops_per_sec \([0-9]*\).*/\1/p' | head -1)

# Never overwrite the committed artifact with a result that was not measured.
if [ -z "$REDIS_SEQ" ] || [ -z "$ASTREAM_SEQ" ] || [ -z "$REDIS_PIPE" ] || [ -z "$ASTREAM_PIPE" ] || [ -z "$REDIS_GC" ] || [ -z "$ASTREAM_GC" ] || [ -z "$REDIS_RELAXED" ] || [ -z "$ASTREAM_RELAXED" ]; then
  echo "bench-vs-redis: missing metric; $OUT left unchanged" >&2
  exit 1
fi

# The CPU model: macOS names it via sysctl, Linux in /proc/cpuinfo; the
# architecture is the fallback, not the answer.
HW_CPU="$(sysctl -n machdep.cpu.brand_string 2>/dev/null \
  || awk -F': *' '/^model name/ { print $2; exit }' /proc/cpuinfo 2>/dev/null || true)"
HW_CPU="${HW_CPU:-$(uname -m)}"
HW_OS="$(uname -s) $(uname -r)"
HW_PROD="$( (sw_vers -productName && sw_vers -productVersion) 2>/dev/null | paste -sd' ' - || true)"

cat > "$OUT" <<EOF
# astream-broker vs Redis — equal-durability throughput matrix

Generated by \`scripts/bench-vs-redis.sh\` (re-runnable). This is an **attached
comparison artifact**, not a green CI claim: the numbers are machine-specific, so
the comparison ships with disclosed hardware + matched
conditions rather than as a hard assertion.

## Disclosed hardware
- CPU: ${HW_CPU}
- OS: ${HW_OS} ${HW_PROD}

## Matched conditions (the honest part)
- Transport: **Unix domain socket** for both (no TCP/loopback skew).
- Payload: **64-byte** record body for all runs.
- Durability tiers compared at matched guarantees:
  1. **1-conn Sequential Strict (\`fsync\`/op)**: ${N} sequential appends awaiting ack (\`Strict\` vs Redis \`appendonly yes\` + \`appendfsync always\`, \`-c 1 -P 1\`).
  2. **1-conn Pipelined Strict (\`window=512\`, \`fsync\` before ack)**: ${PIPE_N} pipelined appends on 1 connection (\`Strict\` group-commit vs Redis \`appendfsync always\`, \`-c 1 -P 512\`).
  3. **16-Client Concurrent Strict (\`fsync\` group-commit)**: ${GC_TOTAL} appends across ${GC_CLIENTS} concurrent connections (\`Strict\` group-commit vs Redis \`appendfsync always\`, \`-c 16 -P 1\`).
  4. **1-conn Sequential Relaxed (page-cache write, no hot-path \`fsync\`)**: ${RELAXED_N} sequential appends (\`Relaxed\` vs Redis \`appendfsync everysec\`, \`-c 1 -P 1\`).

## Result (ops/sec, higher is better)
| Workload & Durability Tier | \`astream-broker\` (ops/s) | Redis (ops/s) |
|---|---:|---:|
| 1-conn Sequential \`Strict\` (\`fsync\` per op) | ${ASTREAM_SEQ} | ${REDIS_SEQ} |
| 1-conn Pipelined \`Strict\` (\`window=512\`, \`fsync\` before ack) | ${ASTREAM_PIPE} | ${REDIS_PIPE} |
| 16-client Concurrent \`Strict\` (\`fsync\` group-commit) | ${ASTREAM_GC} | ${REDIS_GC} |
| 1-conn Sequential \`Relaxed\` (page-cache, no hot-path \`fsync\`) | ${ASTREAM_RELAXED} | ${REDIS_RELAXED} |

At 1-conn sequential \`Strict\` (\`fsync\`/op), both systems are dominated by the host
kernel's single-op \`fsync\` latency (~4 ms on APFS) and land at parity. Under
pipelined and multi-client \`Strict\` workloads, \`astream-broker\`'s group-commit writer
coalesces in-flight records into shared \`fsync\` batches while still acknowledging
only after \`fsync\` completes, alongside \`astream\`'s built-in `(producer_id, producer_seq)`
idempotent deduplication, CRC-32/IEEE framing, replay-from-offset, counterfactual
fork-delivery, and atomic read-process-write.
EOF

echo "seq_strict:   astream=${ASTREAM_SEQ} ops/s  redis=${REDIS_SEQ} ops/s"
echo "pipe_strict:  astream=${ASTREAM_PIPE} ops/s  redis=${REDIS_PIPE} ops/s"
echo "gc16_strict:  astream=${ASTREAM_GC} ops/s  redis=${REDIS_GC} ops/s"
echo "seq_relaxed:  astream=${ASTREAM_RELAXED} ops/s  redis=${REDIS_RELAXED} ops/s"
echo "wrote $OUT"
